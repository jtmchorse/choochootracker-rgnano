#!/usr/bin/env python3
"""Generate the 8x12 ChooChooTracker font for the RG Nano (320x240 logical canvas).

The RG Nano path renders the 40x20 grid on a 320x240 canvas which the platform
layer then area-downscales to 240x240 (0.75x horizontally). The base glyphs are
Terminus Bold 8x14 (Dimitar Zhekov, SIL OFL 1.1). Its 2 px stems sit on source
columns 0-1 and 5-6, which land on whole destination pixels under the 0.75x
filter (dest px k covers source columns [4k/3, 4(k+1)/3)), so stems stay at full
brightness instead of smearing to 0.5/0.25 like 1 px stems do.

Rows 2..13 of the 14 row glyph are kept (cap height 10, 2 rows of descender);
the few glyphs with ink above row 2 are shifted/clipped, see TOP_FIX.

Usage:
  make_font8x12.py PSF_FILE OUT_DIR
    PSF_FILE  Uni3-TerminusBold14.psf (Debian: /usr/share/consolefonts/Uni3-TerminusBold14.psf.gz, gunzip first)
    OUT_DIR   repo tracker/ dir; writes platforms/shared/font8x12.cpp and patches
              packaging/common/fonts/{Default,Console,IBM_VGA}.cnfont
"""
import sys, os, re

CROP_TOP = 2          # first kept source row
H = 12

# glyphs whose ink starts above CROP_TOP: shift up so the top row is row 0 of
# the kept window (they are all small marks that sit above the cap line anyway)
TOP_FIX = {'`': 1}    # '`' occupies source rows 0-1; keep both at out rows 0-1

# manual overrides in out coordinates (12 rows of 8 chars, '#' = ink); applied
# after the crop. Filled by tuning against the squashed review sheet.
OVERRIDES = {
    # 8 vs B was the closest hex pair after the squash; give 8 a round,
    # pinched top half so it no longer matches B's square corners.
    '8': ['..####..',
          '.##..##.',
          '.##..##.',
          '.##..##.',
          '..####..',
          '.##..##.',
          '##...##.',
          '##...##.',
          '##...##.',
          '.#####..',
          '........',
          '........'],
}

def load_psf1(path):
    d = open(path, 'rb').read()
    assert d[0] == 0x36 and d[1] == 0x04, 'not a PSF1 file'
    cs = d[3]
    assert cs == 14, 'expected an 8x14 font'
    return lambda c: list(d[4 + c * cs: 4 + (c + 1) * cs])

def glyph_rows(get, ch):
    src = get(ord(ch))
    if ch in TOP_FIX:
        # mark above the cap line: keep its rows at the top of the cell
        n = TOP_FIX[ch]
        out = src[0:n + 1] + [0] * (H - n - 1)
    else:
        out = src[CROP_TOP:CROP_TOP + H]
    if ch in OVERRIDES:
        out = [int(r.replace('.', '0').replace('#', '1'), 2) for r in OVERRIDES[ch]]
    assert len(out) == H
    return out

def build(psf):
    get = load_psf1(psf)
    return [glyph_rows(get, chr(c)) for c in range(32, 127)]

def write_cpp(glyphs, path):
    with open(path, 'w') as f:
        f.write('#include <stdint.h>\n\n')
        f.write('// 8x12 font for the RG Nano 320x240 canvas. Derived from Terminus Bold 8x14\n')
        f.write('// (SIL OFL 1.1, see packaging/common/fonts/LICENSE-Terminus-OFL.txt).\n')
        f.write('// Generated by tools/rgnano/make_font8x12.py; do not edit by hand.\n')
        f.write('extern "C" const uint8_t font8x12[] = {\n')
        for i, g in enumerate(glyphs):
            ch = chr(32 + i)
            name = "'\\\\'" if ch == '\\' else ("'\\''" if ch == "'" else "'%s'" % ch)
            f.write('  // Character %s\n' % name)
            for r in g:
                f.write('  0x%02X,\n' % r)
        f.write('};\n')

def cnfont_section(glyphs):
    lines = ['resolution: 8x12']
    for g in glyphs:
        lines.append(' '.join('%02x' % r for r in g))
    return '\n'.join(lines) + '\n\n'

def patch_cnfont(path, section):
    t = open(path).read()
    t = re.sub(r'resolution: 8x12\n(?:[0-9a-f ]+\n){95}\n?', '', t)
    i = t.index('resolution: 12x16')
    open(path, 'w').write(t[:i] + section + t[i:])

if __name__ == '__main__':
    psf, out = sys.argv[1], sys.argv[2]
    glyphs = build(psf)
    write_cpp(glyphs, os.path.join(out, 'platforms/shared/font8x12.cpp'))
    sec = cnfont_section(glyphs)
    for n in ('Default', 'Console', 'IBM_VGA'):
        patch_cnfont(os.path.join(out, 'packaging/common/fonts/%s.cnfont' % n), sec)
